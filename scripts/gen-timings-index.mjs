// Regenerates src/data/timings/index.ts from the JSON files in that folder.
// Run after adding or removing bundled timing files: node scripts/gen-timings-index.mjs
import { readdirSync, writeFileSync } from 'node:fs'

const dir = new URL('../src/data/timings/', import.meta.url)
const keys = readdirSync(dir)
  .filter(f => f.endsWith('.json'))
  .map(f => f.slice(0, -5))
  .sort((a, b) => {
    const [qa, sa] = a.split('_').map(Number), [qb, sb] = b.split('_').map(Number)
    return qa - qb || sa - sb
  })

const lines = keys.map(k => `  '${k}': () => import('./${k}.json'),`)
writeFileSync(new URL('index.ts', dir), `// Generated by scripts/gen-timings-index.mjs — do not edit by hand.
// Bundled per-ayah timings keyed "<qdc reciter id>_<surah>", loaded lazily.
export const BUNDLED_TIMINGS: Record<string, () => Promise<unknown>> = {
${lines.join('\n')}
}
`)
console.log(`wrote ${keys.length} entries`)
